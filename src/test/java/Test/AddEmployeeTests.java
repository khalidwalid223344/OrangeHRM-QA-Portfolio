package Test;

import Pages.AddEmployeePage;
import Pages.EmployeeListPage;
import Pages.PersonalDetailsPage;
import Utils.DataFactory;
import Utils.Employee;
import Utils.JsonReader;
import com.fasterxml.jackson.databind.JsonNode;
import io.qameta.allure.Epic;
import io.qameta.allure.Feature;
import io.qameta.allure.Issue;
import io.qameta.allure.Story;
import io.qameta.allure.TmsLink;
import org.testng.Assert;
import org.testng.annotations.BeforeMethod;
import org.testng.annotations.Test;
import org.testng.asserts.SoftAssert;

/**
 * REQ-003 Add New Employee (PIM).
 * TC-PIM-0010 and TC-PIM-0013 repeat the steps of TC-PIM-009 (BUG-003) and are covered by it.
 */
@Epic("OrangeHRM")
@Feature("PIM")
public class AddEmployeeTests extends HrmBaseTest {
    private static final JsonNode DATA = JsonReader.getTestData("employee");

    private AddEmployeePage addPage;

    @BeforeMethod
    public void openAddEmployeePage() {
        loginAsAdmin();
        addPage = new AddEmployeePage(driver).open();
    }

    // TC-PIM-001 | REQ-003
    @Test(description = "TC-PIM-001: Add employee with valid First Name and Last Name")
    @Story("REQ-003") @TmsLink("TC-PIM-001")
    public void TC_PIM_001_verifyAddEmployeeWithValidFirstAndLastName() {
        Employee employee = track(new Employee(DataFactory.firstName(), DataFactory.lastName(), addPage.getEmployeeId()));

        addPage.enterFirstName(employee.firstName()).enterLastName(employee.lastName()).clickSave();

        Assert.assertTrue(addPage.isSaved(), "Employee should be saved and Personal Details displayed");
        PersonalDetailsPage details = new PersonalDetailsPage(driver).waitUntilLoaded();
        Assert.assertEquals(details.getFirstName(), employee.firstName(), "Saved first name");
    }

    // TC-PIM-002 | REQ-003
    @Test(description = "TC-PIM-002: Add employee without First Name")
    @Story("REQ-003") @TmsLink("TC-PIM-002")
    public void TC_PIM_002_verifyAddEmployeeWithoutFirstNameIsRejected() {
        addPage.enterLastName(DataFactory.lastName()).clickSave();

        assertRequired(addPage.getFirstNameError(), "First Name");
        Assert.assertTrue(addPage.isAt(), "Employee must not be saved; user should stay on Add Employee");
    }

    // TC-PIM-003 | REQ-003
    @Test(description = "TC-PIM-003: Add employee without Last Name")
    @Story("REQ-003") @TmsLink("TC-PIM-003")
    public void TC_PIM_003_verifyAddEmployeeWithoutLastNameIsRejected() {
        addPage.enterFirstName(DataFactory.firstName()).clickSave();

        assertRequired(addPage.getLastNameError(), "Last Name");
        Assert.assertTrue(addPage.isAt(), "Employee must not be saved; user should stay on Add Employee");
    }

    // TC-PIM-004 | REQ-003
    @Test(description = "TC-PIM-004: Add employee without First Name and Last Name")
    @Story("REQ-003") @TmsLink("TC-PIM-004")
    public void TC_PIM_004_verifyAddEmployeeWithoutFirstAndLastNameIsRejected() {
        addPage.clickSave();

        assertRequired(addPage.getFirstNameError(), "First Name");
        assertRequired(addPage.getLastNameError(), "Last Name");
        Assert.assertTrue(addPage.isAt(), "Employee must not be saved; user should stay on Add Employee");
    }

    // TC-PIM-005 | REQ-003
    @Test(description = "TC-PIM-005: Add employee with auto-generated Employee ID")
    @Story("REQ-003") @TmsLink("TC-PIM-005")
    public void TC_PIM_005_verifyAddEmployeeWithAutoGeneratedEmployeeId() {
        String generatedId = addPage.getEmployeeId();
        Assert.assertFalse(generatedId.isBlank(), "Employee ID should be auto-generated on the form");
        track(new Employee("n/a", "n/a", generatedId));

        addPage.enterFirstName(DataFactory.firstName()).enterLastName(DataFactory.lastName()).clickSave();

        Assert.assertTrue(addPage.isSaved(), "Employee should be saved");
        Assert.assertEquals(new PersonalDetailsPage(driver).waitUntilLoaded().getEmployeeId(), generatedId,
                "Saved Employee ID should be the auto-generated one");
    }

    // TC-PIM-006 | REQ-003
    @Test(description = "TC-PIM-006: Add employee with manually entered Employee ID")
    @Story("REQ-003") @TmsLink("TC-PIM-006")
    public void TC_PIM_006_verifyAddEmployeeWithManualEmployeeId() {
        String manualId = DataFactory.employeeId();
        track(new Employee("n/a", "n/a", manualId));

        addPage.enterFirstName(DataFactory.firstName()).enterLastName(DataFactory.lastName())
                .enterEmployeeId(manualId).clickSave();

        Assert.assertTrue(addPage.isSaved(),
                "Employee with manual Employee ID '" + manualId + "' should be saved. " + addPage.describeState());
        Assert.assertEquals(new PersonalDetailsPage(driver).waitUntilLoaded().getEmployeeId(), manualId,
                "Saved Employee ID should be the manually entered one");
    }

    // TC-PIM-007 | REQ-003
    @Test(description = "TC-PIM-007: Add employee with duplicate Employee ID")
    @Story("REQ-003") @TmsLink("TC-PIM-007")
    public void TC_PIM_007_verifyAddEmployeeWithDuplicateEmployeeIdIsPrevented() {
        Employee existing = createEmployee(DataFactory.firstName(), DataFactory.lastName());
        addPage = new AddEmployeePage(driver).open();

        addPage.enterFirstName(DataFactory.firstName()).enterLastName(DataFactory.lastName())
                .enterEmployeeId(existing.employeeId()).clickSave();

        String error = addPage.getEmployeeIdError();
        Assert.assertFalse(error.isBlank(), "A duplicate Employee ID message should be displayed for existing id '"
                + existing.employeeId() + "'. " + addPage.describeState());
        Assert.assertTrue(addPage.isAt(), "Employee with a duplicate ID must not be saved. " + addPage.describeState());
    }

    // TC-PIM-008 | REQ-003
    @Test(description = "TC-PIM-008: Newly added employee appears in the Employee List")
    @Story("REQ-003") @TmsLink("TC-PIM-008")
    public void TC_PIM_008_verifyNewEmployeeAppearsInEmployeeList() {
        Employee employee = track(new Employee(DataFactory.firstName(), DataFactory.lastName(), addPage.getEmployeeId()));
        addPage.enterFirstName(employee.firstName()).enterLastName(employee.lastName()).clickSave();
        Assert.assertTrue(addPage.isSaved(), "Employee should be saved");

        EmployeeListPage list = new EmployeeListPage(driver).open().searchByEmployeeId(employee.employeeId());

        Assert.assertTrue(list.getEmployeeIds().contains(employee.employeeId()),
                "New employee should be listed immediately");
        Assert.assertTrue(list.getFirstNames().contains(employee.firstName()), "Listed first name");
    }

    // TC-PIM-009 | REQ-003
    // Related Bug: BUG-003 (no duplicate-name warning); also covers TC-PIM-0010 and TC-PIM-0013
    @Test(description = "TC-PIM-009: Add employee with duplicate First Name and Last Name is allowed and flagged",
            groups = "known-defect")
    @Story("REQ-003") @TmsLink("TC-PIM-009") @Issue("BUG-003")
    public void TC_PIM_009_verifyDuplicateEmployeeNameIsAllowedAndFlagged() {
        Employee existing = createEmployee(DataFactory.firstName(), DataFactory.lastName());
        addPage = new AddEmployeePage(driver).open();
        track(new Employee(existing.firstName(), existing.lastName(), addPage.getEmployeeId()));

        addPage.enterFirstName(existing.firstName()).enterLastName(existing.lastName()).clickSave();

        // Each expectation is reported independently, so the known defect (no warning) cannot hide, or be
        // hidden by, a problem with saving or with the toast.
        SoftAssert soft = new SoftAssert();
        soft.assertTrue(addPage.isSaved(), "Duplicate names must be allowed (not blocked). " + addPage.describeState());
        soft.assertTrue(addPage.hasSuccessToast(), "Save confirmation expected. " + addPage.describeState());
        String feedback = addPage.getFeedbackText();
        soft.assertTrue(containsAny(feedback),
                "BUG-003: a duplicate-name warning/flag should be displayed but feedback was: '" + feedback + "'");
        soft.assertAll();
    }

    // TC-PIM-0011 | REQ-003
    @Test(description = "TC-PIM-0011: Same First Name, different Last Name is added without duplicate flag")
    @Story("REQ-003") @TmsLink("TC-PIM-0011")
    public void TC_PIM_0011_verifySameFirstNameDifferentLastNameIsNotFlagged() {
        Employee existing = createEmployee(DataFactory.firstName(), DataFactory.lastName());
        addPage = new AddEmployeePage(driver).open();
        String newLastName = DataFactory.lastName();
        track(new Employee(existing.firstName(), newLastName, addPage.getEmployeeId()));

        addPage.enterFirstName(existing.firstName()).enterLastName(newLastName).clickSave();

        Assert.assertTrue(addPage.isSaved(), "Employee should be saved. " + addPage.describeState());
        Assert.assertTrue(addPage.hasSuccessToast(), "Save confirmation expected. " + addPage.describeState());
        Assert.assertFalse(containsAny(addPage.getFeedbackText()), "Must not be flagged as duplicate full name");
    }

    // TC-PIM-0012 | REQ-003
    @Test(description = "TC-PIM-0012: Same Last Name, different First Name is added without duplicate flag")
    @Story("REQ-003") @TmsLink("TC-PIM-0012")
    public void TC_PIM_0012_verifySameLastNameDifferentFirstNameIsNotFlagged() {
        Employee existing = createEmployee(DataFactory.firstName(), DataFactory.lastName());
        addPage = new AddEmployeePage(driver).open();
        String newFirstName = DataFactory.firstName();
        track(new Employee(newFirstName, existing.lastName(), addPage.getEmployeeId()));

        addPage.enterFirstName(newFirstName).enterLastName(existing.lastName()).clickSave();

        Assert.assertTrue(addPage.isSaved(), "Employee should be saved. " + addPage.describeState());
        Assert.assertTrue(addPage.hasSuccessToast(), "Save confirmation expected. " + addPage.describeState());
        Assert.assertFalse(containsAny(addPage.getFeedbackText()), "Must not be flagged as duplicate full name");
    }

    private void assertRequired(String actual, String field) {
        Assert.assertTrue(actual.toLowerCase().contains(DATA.get("requiredMessage").asText()),
                "A required-field message should be shown for " + field + " but was: '" + actual + "'");
    }

    private boolean containsAny(String feedback) {
        for (JsonNode indicator : DATA.get("duplicateIndicators")) {
            if (feedback.toLowerCase().contains(indicator.asText())) {
                return true;
            }
        }
        return false;
    }
}
